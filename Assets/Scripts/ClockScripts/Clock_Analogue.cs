using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class Clock_Analogue : MonoBehaviour {
//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------
//
//                                          Simple Clock Script by Andre "AEG" Bürger /VIS-Games (2021)
//  
//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------


    //-------------------------------------------------
    Transform handleSecond;
    Transform handleMinute;
    Transform handleHour;
    //-------------------------------------------------


//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------
void Start()
{
    handleSecond = transform.Find("hand_second");
    handleMinute = transform.Find("hand_minute");
    handleHour   = transform.Find("hand_hour");
}
//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------
void Update()
{
    handleSecond.localEulerAngles = new Vector3(0.0f, 0.0f,  ((360.0f / 60.0f) * System.DateTime.Now.Second) );
    handleMinute.localEulerAngles = new Vector3(0.0f, 0.0f,  ((360.0f / 60.0f) * System.DateTime.Now.Minute) );
    handleHour.localEulerAngles   = new Vector3(0.0f, 0.0f, ((360.0f / 12.0f) * System.DateTime.Now.Hour) + ((360.0f / (60.0f * 12.0f)) * System.DateTime.Now.Minute) );
    //--------------------------------------------------------------------------------------------------------------------------
}
//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------
}
